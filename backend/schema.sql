CREATE TABLE IF NOT EXISTS users (
  id CHAR(36) PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  department VARCHAR(150) NOT NULL,
  role ENUM('employee', 'admin') NOT NULL DEFAULT 'employee',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS activities (
  id CHAR(36) PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  service_type VARCHAR(150) NOT NULL,
  schedule_date DATE NOT NULL,
  schedule_time TIME NOT NULL,
  location VARCHAR(255) NOT NULL,
  registered INT NOT NULL DEFAULT 0,
  total_slots INT NOT NULL,
  cutoff_date DATE NOT NULL,
  cutoff_time TIME NOT NULL,
  description TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS registrations (
  id CHAR(36) PRIMARY KEY,
  employee_id CHAR(36) NOT NULL,
  activity_id CHAR(36) NOT NULL,
  qr_data VARCHAR(500) UNIQUE,
  qr_generated_at DATETIME NULL,
  qr_checked BOOLEAN NOT NULL DEFAULT FALSE,
  checked_in_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY unique_employee_activity (employee_id, activity_id),
  CONSTRAINT fk_registration_employee FOREIGN KEY (employee_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_registration_activity FOREIGN KEY (activity_id) REFERENCES activities(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS reminders (
  id CHAR(36) PRIMARY KEY,
  activity VARCHAR(255) NOT NULL,
  type VARCHAR(100) NOT NULL,
  scheduled_for VARCHAR(100) NOT NULL,
  status ENUM('sent', 'pending') NOT NULL DEFAULT 'pending',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
